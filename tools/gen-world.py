#!/usr/bin/env python3
"""Regenerate wallpaper/js/data/world.js: real land as evenly spaced dots (lat/lon in 0.1 deg).

Input is Natural Earth 110m land (public domain) as GeoJSON:
  curl -L -o /tmp/ne_110m_land.json https://raw.githubusercontent.com/martynafford/natural-earth-geojson/master/110m/physical/ne_110m_land.json
  tools/gen-world.py /tmp/ne_110m_land.json
Dots sit on a Fibonacci sphere (same spacing everywhere); a dot is land if an even-odd ray cast says so.
"""
import json
import os
import sys

import numpy as np

N = 15000
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "wallpaper", "js", "data", "world.js")


def edges(geo):
    segs = []
    for f in geo["features"]:
        g = f["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            for ring in poly:
                r = np.array(ring)[:, :2]
                segs.append(np.hstack([r[:-1], r[1:]]))
    return np.vstack(segs)


def inside(lon, lat, e):
    x1, y1, x2, y2 = e.T
    hit = np.zeros(len(lon), bool)
    for i in range(0, len(lon), 500):
        px, py = lon[i:i + 500, None], lat[i:i + 500, None]
        cross = ((y1 > py) != (y2 > py)) & (px < (x2 - x1) * (py - y1) / (y2 - y1 + 1e-12) + x1)
        hit[i:i + 500] = cross.sum(1) % 2 == 1
    return hit


def main():
    e = edges(json.load(open(sys.argv[1])))
    i = np.arange(N)
    lat = np.degrees(np.arcsin(1 - 2 * (i + .5) / N))
    lon = (np.degrees(i * 2.399963229728653) + 180) % 360 - 180
    m = inside(lon, lat, e)
    pts = np.round(np.stack([lat[m], lon[m]], 1) * 10).astype(int).ravel().tolist()
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen-world.py from Natural Earth 110m land (public domain). Do not edit.\n"
                "// WORLD_LAND = flat [lat, lon, lat, lon, ...] in tenths of a degree, one dot per ~1/%d of the sphere.\n"
                "'use strict';\n\nconst WORLD_LAND = [%s];\n" % (N, ",".join(map(str, pts))))
    print(m.sum(), "land dots of", N, "->", os.path.normpath(OUT))


main()
